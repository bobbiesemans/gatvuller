function leaves(value, prefix = "") {
  if (value === null || typeof value !== "object" || Array.isArray(value)) return [prefix];
  return Object.entries(value).flatMap(([key, child]) => leaves(child, prefix ? `${prefix}.${key}` : key));
}

const base = leaves(ui.nl).sort().join("\n");
for (const locale of ["fr", "en"]) {
  const got = leaves(ui[locale]).sort().join("\n");
  if (got !== base) {
    const a = new Set(leaves(ui.nl));
    const b = new Set(leaves(ui[locale]));
    console.error(locale, "missing", [...a].filter((k) => !b.has(k)));
    console.error(locale, "extra", [...b].filter((k) => !a.has(k)));
    process.exit(1);
  }
}

for (const locale of ["nl", "fr", "en"]) {
  const current = JSON.parse(readFileSync(new URL(`../messages/${locale}.json`, import.meta.url), "utf8"));
  const rest = { ...current };
  delete rest.ui;
  writeFileSync(new URL(`../messages/${locale}.json`, import.meta.url), JSON.stringify({ ...rest, ui: ui[locale] }, null, 2) + "\n");
}
